//! The builders of the file-size planted cases. Each is a scratch git repo, since the check lists
//! the repo's files with `git ls-files`, holding the case's one violation or none. The helpers
//! here are shared by the builders and by the unit tests in `tests.rs`.

use crate::checks::file_size::EXCEPTIONS;
use crate::checks::planted::{Repo, git, scratch};
use crate::scratch::Scratch;

/// A scratch git repo named after `case`, with each `(path, bytes)` of `files` written into it.
pub(super) fn git_repo<T: AsRef<[u8]>>(case: &str, files: &[(&str, T)]) -> Repo {
    let dir = scratch(&format!("file-size-{case}"), files);
    git(&dir, &["init", "-q"]);
    Repo::new(dir)
}

/// A file of `n` lines.
pub(super) fn lines(n: usize) -> String {
    "\n".repeat(n)
}

/// The exception file with `entries` after one `#` header line.
pub(super) fn exceptions(entries: &str) -> (&'static str, String) {
    (EXCEPTIONS, format!("# a header line\n{entries}"))
}


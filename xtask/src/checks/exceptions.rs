//! Exception files: one repo-relative path per line, then whitespace, then the reason the path is
//! exempt. Blank lines and lines starting with `#` are skipped. Every check with an exception
//! list reads it through `load`, so the format has one home.

use crate::checks::{self, line_at};
use crate::violation::Violation;
use std::collections::BTreeSet;
use std::path::Path;

/// One exempt path.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Exception {
    pub path: String,
    pub reason: String,
    /// Its 1-based line in the exception file, for a stale or broken entry.
    pub line: u32,
}

/// The entries of the exception file `file` (repo-relative) under `root`. A missing file means
/// no exceptions. An entry with no reason, or a path listed twice, is a violation at its line;
/// the other entries are still returned.
pub(crate) fn load(root: &Path, file: &str) -> (Vec<Exception>, Vec<Violation>) {
    match checks::read_repo_file(root, file) {
        Ok(Some(text)) => parse(file, &text),
        Ok(None) => (Vec::new(), Vec::new()),
        Err(violation) => (Vec::new(), vec![violation]),
    }
}

/// Parses the text of the exception file `file`.
pub(crate) fn parse(file: &str, text: &str) -> (Vec<Exception>, Vec<Violation>) {
    let mut entries = Vec::new();
    let mut violations = Vec::new();
    let mut seen = BTreeSet::new();
    for (index, raw) in text.lines().enumerate() {
        let entry = raw.trim();
        if entry.is_empty() || entry.starts_with('#') {
            continue;
        }
        let line = line_at(index);
        let (path, reason) = entry
            .split_once(char::is_whitespace)
            .map_or((entry, ""), |(path, reason)| (path, reason.trim()));
        if reason.is_empty() {
            violations.push(checks::violation(
                file,
                line,
                format!("`{path}` has no reason"),
                format!("write why `{path}` is exempt after the path, on the same line"),
            ));
            continue;
        }
        if !seen.insert(path.to_owned()) {
            violations.push(checks::violation(
                file,
                line,
                format!("`{path}` is listed twice"),
                "delete this line and keep the reason on the first one",
            ));
            continue;
        }
        entries.push(Exception {
            path: path.to_owned(),
            reason: reason.to_owned(),
            line,
        });
    }
    (entries, violations)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scratch::Scratch;

    #[test]
    fn entries_keep_their_path_reason_and_line() {
        let (entries, violations) = parse(
            "x.txt",
            "# header\n\nsrc/a.rs  generated by build.rs\n  src/b.rs\tvendored parser  \n",
        );
        assert_eq!(violations, []);
        assert_eq!(
            entries,
            [
                Exception {
                    path: "src/a.rs".into(),
                    reason: "generated by build.rs".into(),
                    line: 3,
                },
                Exception {
                    path: "src/b.rs".into(),
                    reason: "vendored parser".into(),
                    line: 4,
                },
            ]
        );
    }

    #[test]
    fn an_entry_without_a_reason_or_listed_twice_fails_at_its_line() {
        let (entries, violations) = parse("x.txt", "src/a.rs\nsrc/b.rs ok\nsrc/b.rs again\n");
        assert_eq!(entries.len(), 1);
        let printed: Vec<String> = violations.iter().map(ToString::to_string).collect();
        assert_eq!(
            printed,
            [
                "x.txt:1: `src/a.rs` has no reason\n    \
                 fix: write why `src/a.rs` is exempt after the path, on the same line",
                "x.txt:3: `src/b.rs` is listed twice\n    \
                 fix: delete this line and keep the reason on the first one",
            ]
        );
    }

    #[test]
    fn a_missing_file_means_no_exceptions() {
        let dir = Scratch::new("exceptions-missing");
        assert_eq!(load(&dir, "x.txt"), (Vec::new(), Vec::new()));
    }
}

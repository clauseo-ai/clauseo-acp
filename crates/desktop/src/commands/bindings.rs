//! The TypeScript bindings: a test writes every command and the types it names to
//! `ui/app/src/transport/bindings.ts` with tauri-specta, and fails when that changed the file, so
//! a stale file in a commit fails here. Run it once more after it rewrote the file and commit the
//! result: `cargo nextest run -p clauseo-desktop bindings`. It also checks every protocol type
//! exports exactly as protocol's own `WireFormat` export.
//!
//! tauri-specta is a dev-dependency only: the app registers the commands with
//! `tauri::generate_handler!` and carries no specta code.

use std::collections::BTreeSet;
use std::path::PathBuf;

use specta::Format as _;
use specta::datatype::DataType;
use specta_typescript::Typescript;

use super::*;

/// The first lines of the file.
const HEADER: &str = "// Generated by crates/desktop/src/commands/bindings.rs from the desktop commands; \
do not edit.\n// Run `cargo nextest run -p clauseo-desktop bindings` to write it again.";

/// Every command, and the constants the webview reads, on `builder`.
fn with_commands(builder: tauri_specta::Builder<tauri::Wry>) -> tauri_specta::Builder<tauri::Wry> {
    builder
        .commands(tauri_specta::collect_commands![
            dispatch::<tauri::Wry>,
            query::<tauri::Wry>,
            open_stream::<tauri::Wry>,
            subscribe::<tauri::Wry>,
            unsubscribe::<tauri::Wry>,
            ack::<tauri::Wry>,
            answer_permission::<tauri::Wry>,
            pick_folder::<tauri::Wry>,
            display_info::<tauri::Wry>,
        ])
        .constant(
            "KNOWN_DOMAIN_EVENT_KINDS",
            clauseo_protocol::DomainEvent::KINDS,
        )
}

/// The builder the bindings come from, with protocol's types in their `WireFormat` form.
///
/// tauri-specta runs `specta_serde` over every type itself, and has no way to take
/// `WireFormat`. So the wire types go in already mapped, registered before the commands (a type
/// already present is kept), with serde's unified mode (its phased mode refuses
/// `#[serde(other)]`). Each mapped enum is marked untagged: its variants already have their
/// JSON shape, and a second pass would wrap them in a tag again.
fn bindings_builder() -> tauri_specta::Builder<tauri::Wry> {
    let mut wire = clauseo_protocol::WireFormat
        .map_types(&clauseo_protocol::wire_types())
        .unwrap_or_else(|err| panic!("wire format failed: {err}"))
        .into_owned();
    wire.iter_mut(|ndt| {
        if let Some(DataType::Enum(e)) = &mut ndt.ty {
            e.attributes.insert("serde:container:untagged", true);
        }
    });
    with_commands(tauri_specta::Builder::new().types(&wire)).disable_serde_phases()
}

fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../ui/app/src/transport/bindings.ts")
}

/// Each `export type <name> = ...;` block of `ts`, up to the blank line after it.
fn blocks(ts: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = ts;
    while let Some(start) = rest.find("export type ") {
        let block = &rest[start..];
        let end = block.find("\n\n").unwrap_or(block.len());
        out.push(block[..end].trim_end());
        rest = &block[end..];
    }
    out
}

/// Writes the bindings, checks every type protocol exports appears in them exactly as
/// `WireFormat` writes it, then fails when writing changed the file.
#[test]
fn bindings_ts_is_written_and_fails_on_drift() {
    let path = bindings_path();
    let before = std::fs::read_to_string(&path).unwrap_or_default();
    bindings_builder()
        .export(Typescript::default().header(HEADER), &path)
        .unwrap_or_else(|err| panic!("export failed: {err}"));
    let after = std::fs::read_to_string(&path).unwrap_or_default();

    let wire = Typescript::default()
        .export(
            &clauseo_protocol::wire_types(),
            clauseo_protocol::WireFormat,
        )
        .unwrap_or_else(|err| panic!("protocol export failed: {err}"));
    let wire_blocks = blocks(&wire);
    assert!(
        wire_blocks.len() > 100,
        "protocol exported {} types",
        wire_blocks.len()
    );
    let ours: BTreeSet<&str> = blocks(&after).into_iter().collect();
    let differ: Vec<&str> = wire_blocks
        .iter()
        .filter(|block| !ours.contains(*block))
        .map(|block| block.lines().next().unwrap_or_default())
        .collect();
    assert!(
        differ.is_empty(),
        "these types export differently: {differ:#?}"
    );

    assert!(
        before == after,
        "{} was stale and has been written again; review and commit it",
        path.display()
    );
}

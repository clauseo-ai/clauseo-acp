/// The `allowedTools` a Claude session gets with no hook and web search on: no bare `WebFetch`.
pub(crate) fn seeded(web_search: bool) -> Vec<String> {
    web_search
        .then(|| "WebSearch".to_owned())
        .into_iter()
        .chain(
            SEEDED
                .iter()
                .chain(&FETCH_ONLY)
                .map(|host| format!("WebFetch(domain:{host})")),
        )
        .collect()
}

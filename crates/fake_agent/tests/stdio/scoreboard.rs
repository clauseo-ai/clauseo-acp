//! `scenarios/scoreboard.jsonl`, the speed scoreboard's session (R13). This module writes the
//! file's text; nobody edits the file by hand. To regenerate it, set
//! `CLAUSEO_REGENERATE_SCOREBOARD=1` and run `scoreboard_file_matches_its_generator` (see
//! `scenarios/README.md`, "Generated scenarios").
//!
//! The prose and its random choices live in `scoreboard_prose.rs`. Its PRNG has one fixed seed,
//! so the file is the same bytes on every run.

use clauseo_fake_agent::{EXIT_OK, Scenario, scenario_path};
use serde_json::{Value, json};

use crate::harness::{Agent, Scratch, prompt, result};
use crate::scoreboard_prose::{Rng, answer, thought};
use crate::write;

/// The seed of the prose. Changing it changes every byte of the file.
const PROSE_SEED: u64 = 0x5C0E_B0A4_2026_0013;

/// The seed of the chunk sizes, a stream of its own so that they do not depend on the prose.
const CHUNK_SEED: u64 = 0x5C0E_B0A4_2026_0014;

/// Answer chunks hold 1 to 40 characters: one in ten is a short one (1 to 8, a token or two),
/// the rest 28 to 40, so the mean is about 31 and the about 80 KB take about 2,500 chunks.
const CHUNK_MIN: usize = 1;
const CHUNK_MAX: usize = 40;
const SHORT_MAX: usize = 8;
const LONG_MIN: usize = 28;

/// The thought block is sent in this many chunks.
const THOUGHT_CHUNKS: usize = 40;

const DESCRIPTION: &str = "The speed scoreboard's session (R13): the client sends one prompt and \
     answers perm-1 with allow-once. Generated by tests/stdio/scoreboard.rs, do not edit by hand. \
     Played with --pace-ms 5.";

/// The scenario file's text: a header and one JSON step per line, each line ending in `\n`.
pub(crate) fn generate() -> String {
    let parts = parts();
    let (first, second) = split_half(&parts.answer);
    let mut rng = Rng::new(CHUNK_SEED);
    let first = chunks(first, &mut rng);
    let second = chunks(second, &mut rng);

    let mut steps = vec![
        json!({"scenario": "scoreboard", "description": DESCRIPTION, "on_stdin_close": "exit"}),
        json!({"include": "handshake.jsonl"}),
        json!({"expect": {"method": "session/prompt", "as": "p1",
            "params": {"sessionId": "sess-1"}}}),
    ];
    steps.extend(
        split_even(&parts.thought, THOUGHT_CHUNKS)
            .iter()
            .map(|text| message("agent_thought_chunk", "m-thought-1", text)),
    );
    for call in &READS_AND_SEARCHES {
        steps.extend(call_steps(call));
    }
    steps.extend(
        first
            .iter()
            .map(|text| message("agent_message_chunk", "m-answer-1", text)),
    );
    steps.push(pending(&EDIT_MSA));
    steps.push(permission());
    steps.push(json!({"expect_response": {"id": "perm-1",
        "result": {"outcome": {"outcome": "selected", "optionId": "allow-once"}}}}));
    steps.push(running(&EDIT_MSA));
    steps.push(finished(&EDIT_MSA));
    steps.extend(call_steps(&EDIT_SCHEDULE));
    steps.extend(
        second
            .iter()
            .map(|text| message("agent_message_chunk", "m-answer-2", text)),
    );
    steps.push(json!({"respond": {"to": "p1", "result": {"stopReason": "end_turn"}}}));

    let mut text = String::new();
    for step in steps {
        text.push_str(&step.to_string());
        text.push('\n');
    }
    text
}

/// The prose the scenario carries: the thought block, and the answer, which its two
/// `agent_message_chunk` messages carry in order.
pub(crate) struct Parts {
    pub(crate) thought: String,
    pub(crate) answer: String,
}

pub(crate) fn parts() -> Parts {
    let mut rng = Rng::new(PROSE_SEED);
    let thought = thought(&mut rng);
    let answer = answer(&mut rng);
    Parts { thought, answer }
}

/// The answer cut in two at the first paragraph break at or after its middle. The first part
/// ends with a blank line, the second starts at the next block.
fn split_half(answer: &str) -> (&str, &str) {
    let middle = answer.len() / 2;
    let cut = answer
        .match_indices("\n\n")
        .map(|(at, _)| at + 2)
        .find(|at| *at >= middle)
        .unwrap_or(answer.len());
    answer.split_at(cut)
}

/// `text` cut into `parts` pieces of as even a length as characters allow, in order.
fn split_even(text: &str, parts: usize) -> Vec<String> {
    let chars: Vec<char> = text.chars().collect();
    (0..parts)
        .map(|i| {
            let start = i * chars.len() / parts;
            let end = (i + 1) * chars.len() / parts;
            chars[start..end].iter().collect()
        })
        .collect()
}

/// `text` cut into chunks of [`CHUNK_MIN`] to [`CHUNK_MAX`] characters, each taken whole, so no
/// chunk splits a character.
fn chunks(text: &str, rng: &mut Rng) -> Vec<String> {
    let mut out = Vec::new();
    let mut current = String::new();
    let mut count = 0;
    let mut want = chunk_len(rng);
    for c in text.chars() {
        current.push(c);
        count += 1;
        if count == want {
            out.push(std::mem::take(&mut current));
            count = 0;
            want = chunk_len(rng);
        }
    }
    if !current.is_empty() {
        out.push(current);
    }
    out
}

/// The length of the next chunk, in characters.
fn chunk_len(rng: &mut Rng) -> usize {
    if rng.below(10) == 0 {
        rng.between(CHUNK_MIN, SHORT_MAX)
    } else {
        rng.between(LONG_MIN, CHUNK_MAX)
    }
}

/// One `session/update` step with `session_update` as its update.
fn update(session_update: Value) -> Value {
    let mut step = json!({"update": {}});
    step["update"]["update"] = session_update;
    step
}

fn message(kind: &str, message_id: &str, text: &str) -> Value {
    update(json!({"sessionUpdate": kind, "messageId": message_id,
        "content": {"type": "text", "text": text}}))
}

/// A tool call the scenario plays: its three updates and what it reports when it completes.
struct Call {
    id: &'static str,
    kind: &'static str,
    title: &'static str,
    name: &'static str,
    /// The `locations` path, and the path of a diff.
    path: &'static str,
    done: Done,
}

enum Done {
    Text(&'static str),
    Diff {
        old: &'static str,
        new: &'static str,
    },
}


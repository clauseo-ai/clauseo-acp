/// The three updates of a call that needs no permission.
fn call_steps(call: &Call) -> Vec<Value> {
    vec![pending(call), running(call), finished(call)]
}

fn pending(call: &Call) -> Value {
    update(
        json!({"sessionUpdate": "tool_call", "toolCallId": call.id, "title": call.title,
        "name": call.name, "kind": call.kind, "status": "pending",
        "locations": [{"path": call.path}]}),
    )
}

fn running(call: &Call) -> Value {
    update(
        json!({"sessionUpdate": "tool_call_update", "toolCallId": call.id,
        "status": "in_progress"}),
    )
}

fn finished(call: &Call) -> Value {
    let content = match call.done {
        Done::Text(text) => json!([{"type": "content", "content": {"type": "text", "text": text}}]),
        Done::Diff { old, new } => {
            json!([{"type": "diff", "path": call.path, "oldText": old, "newText": new}])
        }
    };
    update(
        json!({"sessionUpdate": "tool_call_update", "toolCallId": call.id,
        "status": "completed", "content": content}),
    )
}

/// The permission request for the edit to `msa.md`, with its four options.
fn permission() -> Value {
    json!({"request": {"id": "perm-1", "method": "session/request_permission",
        "params": {"sessionId": "sess-1",
            "toolCall": {"toolCallId": "tc-edit-1", "title": "Edit msa.md", "kind": "edit",
                "status": "pending"},
            "options": [
                {"optionId": "allow-once", "name": "Allow once", "kind": "allow_once"},
                {"optionId": "allow-always", "name": "Always allow", "kind": "allow_always"},
                {"optionId": "reject-once", "name": "Reject", "kind": "reject_once"}]}}})
}

/// The session update a scenario step sends, or `Null` for a step that sends none.
fn update_of(step: &Value) -> &Value {
    &step["update"]["update"]
}

fn kind_of(update: &Value) -> &str {
    update["sessionUpdate"].as_str().unwrap_or_default()
}

fn text_of(update: &Value) -> &str {
    update["content"]["text"].as_str().unwrap_or_default()
}

const REGENERATE: &str = "CLAUSEO_REGENERATE_SCOREBOARD=1 cargo nextest run -p clauseo-fake_agent \
     scoreboard_file_matches_its_generator";

#[test]
fn scoreboard_file_matches_its_generator() {
    let text = generate();
    let path = scenario_path("scoreboard");
    if std::env::var("CLAUSEO_REGENERATE_SCOREBOARD").as_deref() == Ok("1") {
        write::write(&path, &text).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(&path).unwrap();
    assert!(
        on_disk == text,
        "{} is not what tests/stdio/scoreboard.rs generates; regenerate it with: {REGENERATE}",
        path.display()
    );
}

#[test]
fn scoreboard_has_the_brief_shape() {
    let text = generate();
    assert!(text.ends_with('\n'));
    let lines: Vec<Value> = text
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
        .collect();
    let header = &lines[0];
    assert_eq!(header["scenario"], "scoreboard");
    assert_eq!(header["on_stdin_close"], "exit");
    assert!(
        header["description"]
            .as_str()
            .is_some_and(|d| !d.is_empty())
    );
    assert_eq!(lines[1], json!({"include": "handshake.jsonl"}));
    let expect_prompt = json!({"expect": {"method": "session/prompt", "as": "p1",
        "params": {"sessionId": "sess-1"}}});
    assert_eq!(lines[2], expect_prompt);
    let end = json!({"respond": {"to": "p1", "result": {"stopReason": "end_turn"}}});
    assert_eq!(lines.last().unwrap(), &end);
    Scenario::parse("scoreboard", &text).unwrap();

    // The thought block: 40 chunks of about 600 characters.
    let thought: Vec<&Value> = lines
        .iter()
        .filter(|l| kind_of(update_of(l)) == "agent_thought_chunk")
        .collect();
    assert_eq!(thought.len(), 40);
    assert!(
        thought
            .iter()
            .all(|l| update_of(l)["messageId"] == "m-thought-1")
    );
    let thought_chars: usize = thought
        .iter()
        .map(|l| text_of(update_of(l)).chars().count())
        .sum();
    assert!((550..=700).contains(&thought_chars), "{thought_chars}");

    // Six tool calls, each pending, in progress, completed; read and edit name a path.
    let calls: Vec<&Value> = lines
        .iter()
        .filter(|l| kind_of(update_of(l)) == "tool_call")
        .collect();
    let kinds: Vec<&str> = calls
        .iter()
        .map(|l| update_of(l)["kind"].as_str().unwrap_or_default())
        .collect();
    assert_eq!(kinds, ["read", "read", "search", "search", "edit", "edit"]);
    for call in &calls {
        let id = &update_of(call)["toolCallId"];
        let statuses: Vec<&str> = lines
            .iter()
            .filter(|l| update_of(l)["toolCallId"] == *id)
            .map(|l| update_of(l)["status"].as_str().unwrap_or_default())
            .collect();
        assert_eq!(statuses, ["pending", "in_progress", "completed"], "{id}");
        let kind = update_of(call)["kind"].as_str().unwrap_or_default();
        if kind != "search" {
            let path = update_of(call)["locations"][0]["path"].as_str();
            assert!(path.is_some_and(|p| p.starts_with("{{cwd}}/")), "{id}");
        }
    }

    // One permission request, answered allow-once right after it.
    let asks: Vec<usize> = lines
        .iter()
        .enumerate()
        .filter(|(_, l)| !l["request"].is_null())
        .map(|(index, _)| index)
        .collect();
    assert_eq!(asks.len(), 1);
    let ask = &lines[asks[0]]["request"];
    assert_eq!(ask["method"], "session/request_permission");
    assert_eq!(ask["id"], "perm-1");
    let answer_line = &lines[asks[0] + 1]["expect_response"];
    assert_eq!(answer_line["id"], "perm-1");
    assert_eq!(answer_line["result"]["outcome"]["optionId"], "allow-once");
}

/// The answer: two messages of 1 to 40 characters each, in 2,400 to 2,600 chunks, that make a
/// memo of 78,000 to 82,000 bytes.
#[test]
fn scoreboard_answer_is_a_memo_of_the_brief_size() {
    let lines: Vec<Value> = generate()
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
        .collect();
    let chunks: Vec<(usize, &Value)> = lines
        .iter()
        .enumerate()
        .filter(|(_, l)| kind_of(update_of(l)) == "agent_message_chunk")
        .collect();
    assert!((2400..=2600).contains(&chunks.len()), "{}", chunks.len());
    let edit = lines
        .iter()
        .position(|l| update_of(l)["toolCallId"] == "tc-edit-1")
        .unwrap();
    for (at, chunk) in &chunks {
        let id = update_of(chunk)["messageId"].as_str();
        let want = if *at < edit {
            "m-answer-1"
        } else {
            "m-answer-2"
        };
        assert_eq!(id, Some(want));
        let length = text_of(update_of(chunk)).chars().count();
        assert!(
            (1..=40).contains(&length),
            "{length}: {}",
            text_of(update_of(chunk))
        );
    }
    let answer: String = chunks.iter().map(|(_, l)| text_of(update_of(l))).collect();
    assert!(
        (78_000..=82_000).contains(&answer.len()),
        "{}",
        answer.len()
    );
    assert!(answer.contains('§'));
    assert!(answer.chars().all(|c| c.is_ascii() || c == '§'));

    // The memo's shape: one title, at least ten sections, lists, bold, one table.
    let rows: Vec<&str> = answer.lines().collect();
    let count = |prefix: &str| rows.iter().filter(|r| r.starts_with(prefix)).count();
    assert_eq!(count("# "), 1);
    assert!(count("## ") >= 10, "{}", count("## "));
    assert!(count("- ") >= 1);
    assert!(count("1. ") >= 1);
    assert!(answer.contains("**"));
    let table: Vec<usize> = rows
        .iter()
        .enumerate()
        .filter(|(_, r)| r.starts_with('|'))
        .map(|(index, _)| index)
        .collect();
    assert!(table.len() >= 7, "{}", table.len());
    assert!(
        table.windows(2).all(|pair| pair[1] == pair[0] + 1),
        "one table only"
    );
    assert!(
        rows[table[1]].contains("---"),
        "the second row is the separator"
    );
}

/// The scenario through the binary, as a client that answers the prompt and allows the edit.
#[test]
fn scoreboard_plays_over_stdio() {
    let dir = Scratch::new("scoreboard_plays_over_stdio");
    let mut agent = Agent::start("scoreboard", dir.path());
    agent.handshake(&dir.cwd());
    agent.send(&prompt(2, "Review the master services agreement"));
    let mut answer = String::new();
    let mut chunks = 0;
    // A line the agent wrote is a JSON-RPC notification: its update is in `params`.
    let mut collect = |line: &Value| {
        let update = &line["params"]["update"];
        if kind_of(update) == "agent_message_chunk" {
            answer.push_str(text_of(update));
            chunks += 1;
        }
    };
    let ask = loop {
        let line = agent.read_line();
        if line["method"] == "session/request_permission" {
            break line;
        }
        collect(&line);
    };
    assert_eq!(ask["id"], "perm-1");
    agent.send(&json!({"jsonrpc": "2.0", "id": "perm-1",
        "result": {"outcome": {"outcome": "selected", "optionId": "allow-once"}}}));
    let end = loop {
        let line = agent.read_line();
        if line["id"] == 2 {
            break line;
        }
        collect(&line);
    };
    assert_eq!(end, result(2, json!({"stopReason": "end_turn"})));
    agent.expect_exit(EXIT_OK);
    assert!((2400..=2600).contains(&chunks), "{chunks}");
    let expected = parts().answer;
    assert!(
        answer == expected,
        "the answer the client read is not the generator's prose"
    );
}

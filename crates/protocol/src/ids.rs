/// A 32-byte BLAKE3 digest naming a blob. A human-readable format (JSON) writes its text form, 64
/// lowercase hex characters, and every other format (`MessagePack`) its 32 bytes, so the stored
/// form is 32 bytes and a JSON copy stays readable. Each format decodes only its own form.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[cfg_attr(feature = "specta", derive(specta::Type), specta(type = String))]
pub struct BlobHash([u8; 32]);

impl BlobHash {
    /// Wraps a digest. Every 32 bytes are a valid hash.
    pub const fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    /// The digest's bytes.
    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }
}

impl fmt::Display for BlobHash {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.iter().try_for_each(|byte| write!(f, "{byte:02x}"))
    }
}

pub(crate) fn hex_value(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        _ => None,
    }
}

impl FromStr for BlobHash {
    type Err = Error;

    /// Parses exactly 64 lowercase hex characters.
    fn from_str(text: &str) -> Result<Self, Error> {
        let rule = Error::Format {
            kind: "BlobHash",
            rule: "expected 64 lowercase hex characters",
        };
        let (pairs, rest) = text.as_bytes().as_chunks::<2>();
        if pairs.len() != 32 || !rest.is_empty() {
            return Err(rule);
        }
        let mut bytes = [0u8; 32];
        for (out, &[high, low]) in bytes.iter_mut().zip(pairs) {
            match (hex_value(high), hex_value(low)) {
                (Some(high), Some(low)) => *out = (high << 4) | low,
                _ => return Err(rule),
            }
        }
        Ok(Self(bytes))
    }
}

impl Serialize for BlobHash {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        if serializer.is_human_readable() {
            serializer.collect_str(self)
        } else {
            serializer.serialize_bytes(&self.0)
        }
    }
}

impl<'de> Deserialize<'de> for BlobHash {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        if deserializer.is_human_readable() {
            deserializer.deserialize_str(FromStrVisitor::<Self>::new(
                "a 64-character lowercase hex hash",
            ))
        } else {
            deserializer.deserialize_bytes(DigestBytes)
        }
    }
}

/// The 32 bytes of a digest in a format that is not human-readable. A str is refused, since
/// `deserialize_bytes` gives it only the bytes a binary format holds.
struct DigestBytes;

impl de::Visitor<'_> for DigestBytes {
    type Value = BlobHash;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("32 bytes")
    }

    fn visit_bytes<E: de::Error>(self, v: &[u8]) -> Result<BlobHash, E> {
        match <[u8; 32]>::try_from(v) {
            Ok(bytes) => Ok(BlobHash::from_bytes(bytes)),
            Err(_) => Err(E::invalid_length(v.len(), &self)),
        }
    }
}

